-- 1. TIPOS ENUM PERSONALIZADOS
DO $$ 
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'rol_usuario') THEN
        CREATE TYPE rol_usuario AS ENUM ('admin', 'operador', 'visor');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'estado_dispositivo') THEN
        CREATE TYPE estado_dispositivo AS ENUM ('activo', 'inactivo', 'error');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'tipo_actuador') THEN
        CREATE TYPE tipo_actuador AS ENUM ('bomba', 'ventilador', 'calefactor', 'lampara', 'otro');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'estado_actuador') THEN
        CREATE TYPE estado_actuador AS ENUM ('encendido', 'apagado', 'error');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'tipo_alerta') THEN
        CREATE TYPE tipo_alerta AS ENUM ('minimo', 'maximo');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'nivel_alerta') THEN
        CREATE TYPE nivel_alerta AS ENUM ('bajo', 'medio', 'alto', 'critico');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'accion_actuador') THEN
        CREATE TYPE accion_actuador AS ENUM ('encender', 'apagar');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'origen_comando') THEN
        CREATE TYPE origen_comando AS ENUM ('manual', 'automatico', 'programado');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'estado_comando') THEN
        CREATE TYPE estado_comando AS ENUM ('pendiente', 'ejecutado', 'fallido');
    END IF;
END $$;

-- ============================================================
-- TABLA 1: grupo
-- ============================================================
CREATE TABLE IF NOT EXISTS grupo (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(45)  NOT NULL,
    descripcion VARCHAR(200),
    creado_por  INT,
    creado_en   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_por INT,
    editado_en  TIMESTAMPTZ,
    eliminado   BOOLEAN      NOT NULL DEFAULT FALSE
);

-- ============================================================
-- TABLA 2: usuario
-- ============================================================
CREATE TABLE IF NOT EXISTS usuario (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id      INT           NOT NULL REFERENCES grupo(id) ON DELETE CASCADE,
    nombre        VARCHAR(80)   NOT NULL,
    correo        VARCHAR(120)  NOT NULL UNIQUE,
    password_hash VARCHAR(255)  NOT NULL,
    rol           rol_usuario   NOT NULL DEFAULT 'visor',
    activo        BOOLEAN       NOT NULL DEFAULT TRUE,
    creado_por    INT,
    creado_en     TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_por   INT,
    editado_en    TIMESTAMPTZ,
    eliminado     BOOLEAN       NOT NULL DEFAULT FALSE
);

-- Referencias circulares de auditoría para grupo
DO $$ 
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints WHERE constraint_name = 'fk_grupo_creado_por') THEN
        ALTER TABLE grupo ADD CONSTRAINT fk_grupo_creado_por FOREIGN KEY (creado_por) REFERENCES usuario(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints WHERE constraint_name = 'fk_grupo_editado_por') THEN
        ALTER TABLE grupo ADD CONSTRAINT fk_grupo_editado_por FOREIGN KEY (editado_por) REFERENCES usuario(id);
    END IF;
END $$;

-- ============================================================
-- TABLA 3: magnitud
-- ============================================================
CREATE TABLE IF NOT EXISTS magnitud (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(30)   NOT NULL UNIQUE,
    nombre      VARCHAR(80)   NOT NULL,
    unidad      VARCHAR(16)   NOT NULL,
    rango_min   NUMERIC(8,2),
    rango_max   NUMERIC(8,2),
    creado_por  INT           REFERENCES usuario(id),
    creado_en   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_por INT           REFERENCES usuario(id),
    editado_en  TIMESTAMPTZ,
    eliminado   BOOLEAN       NOT NULL DEFAULT FALSE
);

-- ============================================================
-- TABLA 4: cultivo
-- ============================================================
CREATE TABLE IF NOT EXISTS cultivo (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id    INT           NOT NULL REFERENCES grupo(id) ON DELETE CASCADE,
    nombre      VARCHAR(80)   NOT NULL,
    creado_por  INT           REFERENCES usuario(id),
    creado_en   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_por INT           REFERENCES usuario(id),
    editado_en  TIMESTAMPTZ,
    eliminado   BOOLEAN       NOT NULL DEFAULT FALSE
);

-- ============================================================
-- TABLA 5: zona
-- ============================================================
CREATE TABLE IF NOT EXISTS zona (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id    INT           NOT NULL REFERENCES grupo(id) ON DELETE CASCADE,
    cultivo_id  INT           REFERENCES cultivo(id) ON DELETE SET NULL,
    nombre      VARCHAR(80)   NOT NULL,
    creado_por  INT           REFERENCES usuario(id),
    creado_en   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_por INT           REFERENCES usuario(id),
    editado_en  TIMESTAMPTZ,
    eliminado   BOOLEAN       NOT NULL DEFAULT FALSE
);

-- ============================================================
-- TABLA 6: umbral (PK Compuesta: cultivo_id, magnitud_id)
-- ============================================================
CREATE TABLE IF NOT EXISTS umbral (
    cultivo_id  INT           NOT NULL REFERENCES cultivo(id) ON DELETE CASCADE,
    magnitud_id INT           NOT NULL REFERENCES magnitud(id) ON DELETE CASCADE,
    grupo_id    INT           NOT NULL REFERENCES grupo(id) ON DELETE CASCADE,
    minimo      NUMERIC(8,2)  NOT NULL,
    maximo      NUMERIC(8,2)  NOT NULL,
    creado_por  INT           REFERENCES usuario(id),
    creado_en   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_por INT           REFERENCES usuario(id),
    editado_en  TIMESTAMPTZ,
    eliminado   BOOLEAN       NOT NULL DEFAULT FALSE,
    PRIMARY KEY (cultivo_id, magnitud_id)
);

-- ============================================================
-- TABLA 7: dispositivo (IoT ESP32, Raspberry Pi, etc.)
-- ============================================================
CREATE TABLE IF NOT EXISTS dispositivo (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id        INT                 NOT NULL REFERENCES grupo(id) ON DELETE CASCADE,
    zona_id         INT                 REFERENCES zona(id) ON DELETE SET NULL,
    nombre          VARCHAR(80)         NOT NULL,
    mac             VARCHAR(17)         NOT NULL UNIQUE,
    api_key_hash    CHAR(64),
    intervalo_seg   INT                 NOT NULL DEFAULT 30,
    estado          estado_dispositivo  NOT NULL DEFAULT 'activo',
    ultima_conexion TIMESTAMPTZ,
    creado_por      INT                 REFERENCES usuario(id),
    creado_en       TIMESTAMPTZ         NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_por     INT                 REFERENCES usuario(id),
    editado_en      TIMESTAMPTZ,
    eliminado       BOOLEAN             NOT NULL DEFAULT FALSE
);

-- ============================================================
-- TABLA 8: sensor
-- ============================================================
CREATE TABLE IF NOT EXISTS sensor (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id       INT          NOT NULL REFERENCES grupo(id) ON DELETE CASCADE,
    dispositivo_id INT          NOT NULL REFERENCES dispositivo(id) ON DELETE CASCADE,
    magnitud_id    INT          NOT NULL REFERENCES magnitud(id),
    codigo         VARCHAR(30)  NOT NULL UNIQUE,
    modelo         VARCHAR(40),
    cal_seco       INT          DEFAULT 0,
    cal_mojado     INT          DEFAULT 1023,
    activo         BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_por     INT          REFERENCES usuario(id),
    creado_en      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_por    INT          REFERENCES usuario(id),
    editado_en     TIMESTAMPTZ,
    eliminado      BOOLEAN      NOT NULL DEFAULT FALSE
);

-- ============================================================
-- TABLA 9: actuador
-- ============================================================
CREATE TABLE IF NOT EXISTS actuador (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id       INT              NOT NULL REFERENCES grupo(id) ON DELETE CASCADE,
    dispositivo_id INT              NOT NULL REFERENCES dispositivo(id) ON DELETE CASCADE,
    tipo           tipo_actuador    NOT NULL,
    nombre         VARCHAR(80)      NOT NULL,
    estado         estado_actuador  NOT NULL DEFAULT 'apagado',
    creado_por     INT              REFERENCES usuario(id),
    creado_en      TIMESTAMPTZ      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_por    INT              REFERENCES usuario(id),
    editado_en     TIMESTAMPTZ,
    eliminado      BOOLEAN          NOT NULL DEFAULT FALSE
);

-- ============================================================
-- TABLA 10: lectura (Histórico de telemetría IoT)
-- ============================================================
CREATE TABLE IF NOT EXISTS lectura (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id    INT           NOT NULL REFERENCES grupo(id) ON DELETE CASCADE,
    sensor_id   INT           NOT NULL REFERENCES sensor(id) ON DELETE CASCADE,
    valor       NUMERIC(8,2)  NOT NULL,
    fecha_hora  TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    creado_por  INT           REFERENCES usuario(id),
    creado_en   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_por INT           REFERENCES usuario(id),
    editado_en  TIMESTAMPTZ,
    eliminado   BOOLEAN       NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_lectura_sensor ON lectura(sensor_id);
CREATE INDEX IF NOT EXISTS idx_lectura_fecha  ON lectura(fecha_hora DESC);
CREATE INDEX IF NOT EXISTS idx_lectura_grupo  ON lectura(grupo_id);

-- ============================================================
-- TABLA 11: lectura_actual (Caché - 1 fila por sensor)
-- ============================================================
CREATE TABLE IF NOT EXISTS lectura_actual (
    sensor_id   INT           PRIMARY KEY REFERENCES sensor(id) ON DELETE CASCADE,
    grupo_id    INT           NOT NULL REFERENCES grupo(id) ON DELETE CASCADE,
    valor       NUMERIC(8,2)  NOT NULL,
    fecha_hora  TIMESTAMPTZ   NOT NULL,
    creado_por  INT           REFERENCES usuario(id),
    creado_en   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_por INT           REFERENCES usuario(id),
    editado_en  TIMESTAMPTZ,
    eliminado   BOOLEAN       NOT NULL DEFAULT FALSE
);

-- ============================================================
-- TABLA 12: alerta
-- ============================================================
CREATE TABLE IF NOT EXISTS alerta (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id     INT           NOT NULL REFERENCES grupo(id) ON DELETE CASCADE,
    zona_id      INT           REFERENCES zona(id) ON DELETE SET NULL,
    sensor_id    INT           NOT NULL REFERENCES sensor(id) ON DELETE CASCADE,
    atendida_por INT           REFERENCES usuario(id),
    tipo         tipo_alerta   NOT NULL,
    nivel        nivel_alerta  NOT NULL DEFAULT 'medio',
    valor        NUMERIC(8,2)  NOT NULL,
    limite       NUMERIC(8,2)  NOT NULL,
    mensaje      VARCHAR(200),
    fecha_hora   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atendida     BOOLEAN       NOT NULL DEFAULT FALSE,
    atendida_en  TIMESTAMPTZ,
    creado_por   INT           REFERENCES usuario(id),
    creado_en    TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_por  INT           REFERENCES usuario(id),
    editado_en   TIMESTAMPTZ,
    eliminado    BOOLEAN       NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_alerta_sensor   ON alerta(sensor_id);
CREATE INDEX IF NOT EXISTS idx_alerta_atendida ON alerta(atendida);

-- ============================================================
-- TABLA 13: comando_actuador
-- ============================================================
CREATE TABLE IF NOT EXISTS comando_actuador (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_id      INT              NOT NULL REFERENCES grupo(id) ON DELETE CASCADE,
    usuario_id    INT              NOT NULL REFERENCES usuario(id),
    actuador_id   INT              NOT NULL REFERENCES actuador(id) ON DELETE CASCADE,
    accion        accion_actuador  NOT NULL,
    duracion_seg  INT,
    origen        origen_comando   NOT NULL DEFAULT 'manual',
    estado        estado_comando   NOT NULL DEFAULT 'pendiente',
    confirmado_en TIMESTAMPTZ,
    creado_por    INT              REFERENCES usuario(id),
    creado_en     TIMESTAMPTZ      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_por   INT              REFERENCES usuario(id),
    editado_en    TIMESTAMPTZ,
    eliminado     BOOLEAN          NOT NULL DEFAULT FALSE
);
